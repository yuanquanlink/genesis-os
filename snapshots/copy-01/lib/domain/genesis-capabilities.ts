export type GenesisCapabilityStatus = keyof typeof capabilityStatusDefinitions;

export type GenesisCapability = {
  capability_id: string;
  name: string;
  domain: string;
  description: string;
  introduced_version: string;
  current_status: GenesisCapabilityStatus;
  required_surfaces: readonly string[];
  required_routes: readonly string[];
  required_tables: readonly string[];
  required_tests: readonly string[];
  formal_state_rules: readonly string[];
  data_safety_rules: readonly string[];
  can_be_removed: false;
  notes: readonly string[];
};

const formalStateRules = [
  "AI output is read-only analysis or a candidate until an explicit user decision creates formal state.",
  "AI must not directly approve Goal, Ability, Evidence, Strategy, Mission, Memory, Daily Plan, or long-term profile state.",
] as const;

const dataSafetyRules = [
  "Preserve raw user-owned input and provenance before derived analysis.",
  "Do not expose secrets, silently delete formal data, or mix demo/test records into user context.",
] as const;

function capability(
  input: Omit<GenesisCapability, "formal_state_rules" | "data_safety_rules" | "can_be_removed"> & {
    formal_state_rules?: readonly string[];
    data_safety_rules?: readonly string[];
  },
): GenesisCapability {
  return {
    ...input,
    formal_state_rules: input.formal_state_rules ?? formalStateRules,
    data_safety_rules: input.data_safety_rules ?? dataSafetyRules,
    can_be_removed: false,
  };
}

